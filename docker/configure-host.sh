#!/usr/bin/env bash
# Write docker/.env for this host: user ids, X11 access, GPU overlay and robot source checkouts.
# Safe to re-run (for example after logging in again, when the X auth file changes).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
env_file="$here/.env"
declare -A keep=()
if [[ -f "$env_file" ]]; then  # keep user-chosen robot source settings
  while IFS='=' read -r key value; do
    [[ "$key" =~ ^(CINDY_[A-Z_]+|DWARL_WORK)$ ]] && keep[$key]="$value"
  done < "$env_file"
fi

files="compose.yaml"
if docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q nvidia \
   || docker info 2>/dev/null | grep -q 'nvidia.com/gpu'; then
  files="$files:compose.gpu.yaml"
  gpu="NVIDIA GPU enabled"
elif command -v nvidia-smi >/dev/null 2>&1; then
  gpu="NVIDIA GPU found but Docker cannot use it: install the NVIDIA container toolkit (docker/README.md), then re-run"
else
  gpu="no NVIDIA GPU: training and rendering run on the CPU"
fi
if [[ -n "${COMPOSE_EXTRA:-}" ]]; then files="$files:$COMPOSE_EXTRA"; fi

xauth_file="/dev/null"
if [[ -n "${XAUTHORITY:-}" && -f "$XAUTHORITY" ]]; then xauth_file="$XAUTHORITY"
elif [[ -f "$HOME/.Xauthority" ]]; then xauth_file="$HOME/.Xauthority"; fi
if command -v xhost >/dev/null 2>&1 && [[ -n "${DISPLAY:-}" ]]; then
  xhost "+SI:localuser:$(id -un)" >/dev/null 2>&1 || true   # same-user containers may open windows
fi

{
  echo "# Generated by docker/configure-host.sh on $(date -I)"
  echo "COMPOSE_FILE=$files"
  echo "HOST_UID=$(id -u)"
  echo "HOST_GID=$(id -g)"
  echo "DISPLAY=${DISPLAY:-:0}"
  echo "XAUTH_FILE=$xauth_file"
  for key in "${!keep[@]}"; do echo "$key=${keep[$key]}"; done
} > "$env_file"
mkdir -p "${keep[DWARL_WORK]:-$here/../work}"
echo "Wrote $env_file ($gpu)"
